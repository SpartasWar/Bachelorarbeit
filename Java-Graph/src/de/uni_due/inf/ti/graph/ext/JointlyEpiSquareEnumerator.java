package de.uni_due.inf.ti.graph.ext;

import de.uni_due.inf.ti.graph.Graph;
import de.uni_due.inf.ti.graph.Morphism;
import de.uni_due.inf.ti.graph.Node;
import de.uni_due.inf.ti.util.Enumerator;

/**
 * Enumerates jointly epi squares that close a given span of arrows.
 *
 * Given a span <code>L <-a_l-- U --a_r-> R</code>, we are looking for diagrams like these:
 *
 * <pre>
 *  U --a_r-> R
 *  |         |
 * a_l       d_r
 *  |         |
 *  v         v
 *  L --d_l-> J
 * </pre>
 *
 * where d_l, d_r are jointly epi and the diagram commutes.
 * @see JointlyEpiMorphismsEnumerator
 */
public class JointlyEpiSquareEnumerator extends Enumerator<Square> {
	private final Span a;
	private final JointlyEpiMorphismsEnumerator jeme;

	public JointlyEpiSquareEnumerator(Morphism a_l, Morphism a_r) {
		this(new Span(a_l, a_r));
	}

	public JointlyEpiSquareEnumerator(Span a) {
		this.a = a;

		/*
		 * We construct jointly epi squares by computing jointly epi morphisms and
		 * filtering out those which do not form a commuting square.
		 *
		 * Surely there must be a more efficient way.
		 *
		 * FIXME: ^ MASSIVE bottleneck, in some cases this results in sifting through 145k JE morphisms
		 * to end up with a single JE square. (Investigate this)
		 *
		 * Idea: Do the partial morphism enumeration ourselves and supply a base morphism that
		 * relates all objects with a common preimage or something?
		 * Because assume we have elements that have a common preimage in the top graph,
		 * but they are not related in the partial morphism,
		 * then the JEM generator would add them as separate elements.
		 * If that happens however the resulting square definitely does not commute and gets thrown away
		 *
		 * Maybe we should switch around the code for JEM and JES? JES is the base case,
		 * and JEMs are generated by supplying empty top graph,
		 * then cutting off the top half of the square for the results
		 */
		/*
		 * Construct the "base" morphism that relates exactly the parts of L and R
		 * that have a common preimage. This (hopefully) causes the enumerator to ignore
		 * those morphisms that wouldn't produce commuting squares anyway.
		 * TODO: Check how it behaves with noninjective morphisms.
		 * TODO: Check if this idea is even correct!
		 */
		Morphism base = a.getLeftMorphism().getInverse().compose(a.getRightMorphism());
		this.jeme = new JointlyEpiMorphismsEnumerator(a.getLeftGraph(), a.getRightGraph(), base);
	}

	@Override
	public Square next() {
		while (true) {
			Cospan d = this.jeme.next();
			if (d == null) {
				return null;
			}

			Square s = new Square(this.a, d);
			if (s.isCommuting()) {
				return s;
			}
		}
	}
}
